function [problem, options] = apcDefaultProblem(bundle)
%APCDEFAULTPROBLEM Explicit numeric contract suitable for compiled callers.
apcValidateBundle(bundle);
inputCount=numel(bundle.InputNames); outputCount=numel(bundle.OutputNames);
problem=struct('InputNames',{bundle.InputNames},'OutputNames',{bundle.OutputNames}, ...
    'LowerBounds',bundle.TrainingMin,'UpperBounds',bundle.TrainingMax, ...
    'CurrentPoint',(bundle.TrainingMin+bundle.TrainingMax)/2, ...
    'MaxMove',inf(1,inputCount),'Step',zeros(1,inputCount), ...
    'Goals',{repmat({'target'},1,outputCount)},'Targets',zeros(1,outputCount), ...
    'Scales',ones(1,outputCount),'Weights',ones(1,outputCount), ...
    'ResponseLower',-inf(1,outputCount),'ResponseUpper',inf(1,outputCount));
options=struct('PopulationSize',64,'Generations',25,'Seed',42, ...
    'MaxSeconds',15,'Tolerance',1e-8,'AllowExtrapolation',false,'ArchiveLimit',300);
end
